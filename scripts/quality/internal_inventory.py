"""Generate ``spark/internal_inventory.py``, the fixed inventory of the trusted code locations that a sealed job's diagnostic line may name.

Run from the repository root: ``.venv/bin/python -m scripts.quality.internal_inventory`` writes the module, and ``--check`` only compares it (exit 1 when it is
stale). The inventory maps each tracked ``.py`` file of the project's packages (``spark.internal_classes.PACKAGES``) to the sorted names of the functions,
methods and classes that its source defines (the names of the code objects that a frame can carry). The module itself is left out: it is data.
``spark/internal_diagnostic.py`` names a frame only when its file and its function are in the inventory. The fast test ``test_internal_inventory`` compares the
module with this generator's output for the files that ``git ls-files`` lists, so a new, renamed or removed file or function fails it until the module is
regenerated.
"""

from __future__ import annotations

import ast
import re
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path

from scripts.ingestion.output_file import replace_owned_file
from scripts.process import run_command
from spark.internal_classes import NAME_LIMIT, PACKAGES, PATH_LIMIT

FOLDER = "spark"
MODULE = "internal_inventory.py"
GENERATED = f"{FOLDER}/{MODULE}"
GIT_TIMEOUT_SECONDS = 60
LINE_WIDTH = 150
PATH_FORM = re.compile(r"[A-Za-z0-9_]+(?:/[A-Za-z0-9_]+)*\.py")
NAME_FORM = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
HEADER = (
    '"""The fixed inventory of the trusted code locations that a sealed job\'s diagnostic line may name (``spark/internal_diagnostic.py``).\n'
    "\n"
    "GENERATED by ``scripts/quality/internal_inventory.py`` from the tracked files of the project's packages: do not edit. Each tracked ``.py`` file\n"
    "maps to the sorted names of the functions, methods and classes that its source defines. Regenerate with\n"
    "``.venv/bin/python -m scripts.quality.internal_inventory``; the fast test "
    '``test_internal_inventory`` fails while the module differs from the tracked code.\n"""\n'
    "\n"
    "# fmt: off\n"
    "INVENTORY: dict[str, tuple[str, ...]] = {\n"
)
FOOTER = "}\n# fmt: on\n"


class InventoryError(Exception):
    """A tracked file that the inventory cannot hold (a name or a path outside the form that the line carries, or a source that does not parse)."""


def package_files(listed: Sequence[str]) -> list[str]:
    """The ``.py`` files of ``listed`` (tracked paths) that are under a package of the project, sorted, without the generated module."""
    return sorted(path for path in listed if path.endswith(".py") and path.split("/")[0] in PACKAGES and path != GENERATED)


def defined_names(path: str, source: str) -> list[str]:
    """The sorted names of the functions, methods and classes of ``source`` at any depth."""
    try:
        tree = ast.parse(source)
    except SyntaxError as error:
        raise InventoryError(f"{path}: the source does not parse (line {error.lineno})") from error
    names = {node.name for node in ast.walk(tree) if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef)}
    for name in names:
        if len(name) > NAME_LIMIT or NAME_FORM.fullmatch(name) is None:
            raise InventoryError(f"{path}: the name {name!r} is longer than {NAME_LIMIT} characters or has a character outside [A-Za-z0-9_]")
    return sorted(names)


def inventory_of(sources: Mapping[str, str]) -> dict[str, list[str]]:
    """The inventory of ``sources`` (tracked path to source text), in path order."""
    result: dict[str, list[str]] = {}
    for path in sorted(sources):
        if len(path) > PATH_LIMIT or PATH_FORM.fullmatch(path) is None:
            raise InventoryError(f"{path}: the path is longer than {PATH_LIMIT} characters or has a character outside [A-Za-z0-9_/]")
        result[path] = defined_names(path, sources[path])
    return result


def render(inventory: Mapping[str, Sequence[str]]) -> str:
    """The text of the generated module: one entry per file, the names wrapped inside ``LINE_WIDTH`` characters."""
    lines: list[str] = []
    for path in sorted(inventory):
        names = sorted(inventory[path])
        if not names:
            lines.append(f'    "{path}": (),')
            continue
        lines.append(f'    "{path}": (')
        current = "       "
        for name in names:
            piece = f' "{name}",'
            if len(current) + len(piece) > LINE_WIDTH:
                lines.append(current)
                current = "       "
            current += piece
        lines.append(current)
        lines.append("    ),")
    return HEADER + "\n".join(lines) + ("\n" if lines else "") + FOOTER


def read_sources(root: Path) -> dict[str, str]:
    """The source of every tracked file of the packages in the checkout at ``root``."""
    listing = run_command("git", ["ls-files", "-z", "--", "*.py"], cwd=root, timeout=GIT_TIMEOUT_SECONDS, check=True).stdout
    return {path: (root / path).read_text(encoding="utf-8") for path in package_files(listing.split("\0"))}


def build(root: Path) -> dict[str, list[str]]:
    """The inventory of the tracked files in the checkout at ``root``."""
    return inventory_of(read_sources(root))


def check(root: Path, sources: Mapping[str, str]) -> int:
    """0 when the module at ``root`` is what ``sources`` give, else 1 with the fix on standard error."""
    if (root / GENERATED).read_text(encoding="utf-8") == render(inventory_of(sources)):
        return 0
    sys.stderr.write(f"{GENERATED} is stale: run .venv/bin/python -m scripts.quality.internal_inventory\n")
    return 1


def write(root: Path, sources: Mapping[str, str]) -> int:
    """Write the module for ``sources`` at ``root`` when it differs (a rerun that changes nothing writes nothing). Returns 0."""
    folder = root / FOLDER
    text = render(inventory_of(sources))
    if not (folder / MODULE).exists() or (folder / MODULE).read_text(encoding="utf-8") != text:
        replace_owned_file(folder / MODULE, text, state_root=folder, mode=0o644)
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    arguments = list(sys.argv[1:] if argv is None else argv)
    if arguments not in ([], ["--check"]):
        sys.stderr.write("usage: python -m scripts.quality.internal_inventory [--check]\n")
        return 2
    root = Path(__file__).resolve().parents[2]
    sources = read_sources(root)  # a file that the inventory cannot hold raises InventoryError with its path and the reason
    return check(root, sources) if arguments else write(root, sources)


if __name__ == "__main__":
    sys.exit(main())
