"""The plain Git ``pre-push`` hook that runs the push gate.

Pre-commit gives its hooks no standard input and stashes the unstaged changes while they run, so the gate cannot be a pre-commit hook: it must read the
``<local ref> <local sha> <remote ref> <remote sha>`` lines that Git writes to a pre-push hook, and it must see the working tree as it is. This hook reads
Git's standard input once, runs ``scripts.quality.push_gate`` with it and, when the gate passes, runs an older ``pre-push`` hook of the owner with the same
arguments and input. No file of saved input exists.

An older ``pre-push`` hook that this project did not ship is kept as ``pre-push.previous`` (``KeptHookError`` when that name is taken, nothing overwritten).
A saved owner hook that the setup cannot carry over to that name raises ``KeptHookError`` too, before anything changes: the hook that the setup writes runs
only ``pre-push.previous``, so an owner's hook left in ``pre-push.legacy.previous`` behind another file, or in a regular ``pre-push.legacy``, would
stop running. The same refusal applies when the current hook is already installed: ``installed`` is False, so setup never reports an installed and
verified hook while an owner's hook sits at ``pre-push.legacy``. Every hook file is read and compared as bytes, so no byte of an owner's hook can raise a
decode error.
The installer also removes what earlier versions of this project left in the hooks folder: the guards that they kept as ``pre-push.legacy`` (one refused a
push that sent only deletes) and the ``pre-push`` script that ``pre-commit install`` wrote when the gate was a pre-commit hook. The file is written the way
``worktree_scan_hook`` writes the scan hook: ``replace_owned_file`` in the hooks folder.
"""

from __future__ import annotations

import os
from pathlib import Path

from scripts.ingestion.closed import ClosedInputError
from scripts.ingestion.output_file import replace_owned_file
from scripts.quality import push_gate, worktree_scan_hook

HOOK_NAME = "pre-push"
KEPT_NAME = "pre-push.previous"
PREDECESSOR_NAME = "pre-push.legacy"
ORPHAN_NAME = "pre-push.legacy.previous"
KEPT_REFUSAL = (
    f"{HOOK_NAME}, {PREDECESSOR_NAME} or {ORPHAN_NAME} holds an owner's hook that the setup cannot keep as {KEPT_NAME} (that name is taken, another hook "
    f"needs it or a file in the way would stop it): compare the files, move one away as the owner, then run setup again; nothing was changed"
)
PRE_COMMIT_MARKER = b"File generated by pre-commit"
OWN_MARKER = "# project push hook, gate version "
REQUIRED_GATE_VERSION = push_gate.GATE_VERSION
GATE_FILE = "scripts/quality/push_gate.py"
# The hook of the version before the gate had a version, byte for byte.
ROUND_TWO_TEXT = (
    "#!/bin/sh\n"
    'refs="$(cat)"\n'
    'printf \'%s\\n\' "$refs" | .venv/bin/python -m scripts.quality.push_gate "$@" || exit $?\n'
    f'previous="$(dirname "$0")/{KEPT_NAME}"\n'
    'if [ -x "$previous" ]; then printf \'%s\\n\' "$refs" | "$previous" "$@"; exit $?; fi\n'
)
_VERSION_CHECK = (
    f"{OWN_MARKER}@VERSION@\n"
    f"version=\"$(sed -n 's/^GATE_VERSION = \\([0-9][0-9]*\\)$/\\1/p' {GATE_FILE} 2>/dev/null)\"\n"
    'if [ -z "$version" ] || [ "$version" -lt @VERSION@ ]; then\n'
    "  echo \"push gate stopped by gate version: this worktree's gate is missing, has no version or is older than version @VERSION@, "
    'which the installed hook requires: run make setup in the main checkout, or rebase this branch on the one that holds the gate" >&2\n'
    "  exit 1\n"
    "fi\n"
)


# An input that cannot be read is a failed push, not an empty one: the status of ``cat`` decides.
_READ_INPUT = (
    'refs="$(cat)" || {\n  echo "push gate stopped by input: the list of refs that Git sends could not be read, so what is sent is unknown" >&2\n  exit 1\n}\n'
)


def hook_text(version: int) -> str:
    """The shared hook for gate ``version``: it refuses a worktree whose gate is missing, has no version constant or is older, and otherwise runs the gate."""
    checked = ROUND_TWO_TEXT.replace("#!/bin/sh\n", "#!/bin/sh\n" + _VERSION_CHECK.replace("@VERSION@", str(version)), 1)
    return checked.replace('refs="$(cat)"\n', _READ_INPUT, 1)


HOOK_TEXT = hook_text(REQUIRED_GATE_VERSION)
# The guards that earlier versions of this project installed as pre-push.legacy, byte for byte.
_TRACKED = (
    'echo "push gate stopped by tracked changes: tracked files have uncommitted changes, so the checks would not read the pushed commit: '
    'commit or restore them" >&2\n  echo "$changed" >&2\n  exit 1\nfi\n'
)
_PREVIOUS = 'previous="$(dirname "$0")/pre-push.legacy.previous"\n'
PREDECESSOR_TEXTS = (
    '#!/bin/sh\nchanged="$(git status --porcelain --untracked-files=no)"\nif [ -n "$changed" ]; then\n  '
    + _TRACKED
    + _PREVIOUS
    + 'if [ -x "$previous" ]; then exec "$previous" "$@"; fi\n',
    '#!/bin/sh\nrefs="$(git rev-parse --git-path push_gate_refs)"\n{ echo "remote $1"; cat; } > "$refs"\n'
    'sent="$(sed 1d "$refs" | awk \'$2 !~ /^0+$/\')"\n'
    'changed="$(git status --porcelain --untracked-files=no)"\nif [ -n "$changed" ] && [ -n "$sent" ]; then\n  '
    + _TRACKED
    + _PREVIOUS
    + 'if [ -x "$previous" ]; then sed 1d "$refs" | "$previous" "$@"; exit $?; fi\n',
)
PREDECESSOR_BYTES = tuple(text.encode() for text in PREDECESSOR_TEXTS)
PUSH_HOOK = worktree_scan_hook.LegacyHook(HOOK_NAME, KEPT_NAME, HOOK_TEXT)


def hooks_folder(root: Path) -> Path:
    return worktree_scan_hook.hook_path(root, PUSH_HOOK).parent


def predecessors(root: Path) -> list[Path]:
    """The files in the hooks folder that earlier versions left: a shipped guard, a ``pre-push`` script that pre-commit wrote and a hook of this project
    for another gate version or from before the gate had one."""
    hooks = hooks_folder(root)
    legacy, own = hooks / PREDECESSOR_NAME, hooks / HOOK_NAME
    found = [legacy] if legacy.is_file() and legacy.read_bytes() in PREDECESSOR_BYTES else []
    if own.is_file():
        text = own.read_bytes()
        if PRE_COMMIT_MARKER in text or text == ROUND_TWO_TEXT.encode() or (OWN_MARKER.encode() in text and text != HOOK_TEXT.encode()):
            found.append(own)
    return found


def installed(root: Path) -> bool:
    hooks = hooks_folder(root)
    return (
        worktree_scan_hook.installed(root, PUSH_HOOK)
        and not predecessors(root)
        and not os.path.lexists(hooks / ORPHAN_NAME)
        and not (hooks / PREDECESSOR_NAME).is_file()
    )


def install(root: Path) -> bool:
    """Write the hook, remove what earlier versions left and return True, or False when nothing changed.

    The hook of an earlier version, or a script that pre-commit wrote, is replaced in place and atomically, so the old hook stays active until the new one is
    whole. The owner's hook that a shipped guard kept as ``pre-push.legacy.previous`` is moved to ``pre-push.previous``, so that it keeps running. An older hook
    that cannot be kept, and any saved owner hook that stays behind, raise ``KeptHookError`` before anything is changed.
    """
    hooks = hooks_folder(root)
    stale = predecessors(root)
    own = hooks / HOOK_NAME
    guards = [path for path in stale if path != own]
    orphan = hooks / ORPHAN_NAME
    legacy = hooks / PREDECESSOR_NAME
    migrate = os.path.lexists(orphan) and (bool(guards) or not os.path.lexists(legacy))
    moves_to_kept = int(migrate) + int(own not in stale and worktree_scan_hook.would_keep(root, PUSH_HOOK))
    stays_behind = os.path.lexists(orphan) and not migrate
    legacy_hook_lost = legacy not in guards and legacy.is_file()
    if stays_behind or legacy_hook_lost or moves_to_kept > 1 or (moves_to_kept and os.path.lexists(hooks / KEPT_NAME)):
        raise worktree_scan_hook.KeptHookError(KEPT_REFUSAL)
    kept = hooks / KEPT_NAME
    if own in stale:
        try:
            replace_owned_file(own, HOOK_TEXT, state_root=hooks, mode=worktree_scan_hook.HOOK_MODE)
        except ClosedInputError:
            raise OSError("the hook could not be written") from None
        written = True
    else:
        written = worktree_scan_hook.install(root, PUSH_HOOK)
    for path in guards:
        path.unlink()
    if migrate:
        orphan.rename(kept)
    return written or bool(guards) or migrate
