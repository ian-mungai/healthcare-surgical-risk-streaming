"""The plain Git ``pre-push`` hook that runs the push gate.

Pre-commit gives its hooks no standard input and stashes the unstaged changes while they run, so the gate cannot be a pre-commit hook: it must read the
``<local ref> <local sha> <remote ref> <remote sha>`` lines that Git writes to a pre-push hook, and it must see the working tree as it is. This hook reads
Git's standard input once, runs ``scripts.quality.push_gate`` with it and, when the gate passes, runs an older ``pre-push`` hook of the owner with the same
arguments and input. No file of saved input exists.

An older ``pre-push`` hook that this project did not ship is kept as ``pre-push.previous`` (``KeptHookError`` when that name is taken, nothing overwritten).
The installer also removes what earlier versions of this project left in the hooks folder: the guards that they kept as ``pre-push.legacy`` (one refused a
push that sent only deletes) and the ``pre-push`` script that ``pre-commit install`` wrote when the gate was a pre-commit hook. The file is written the way
``worktree_scan_hook`` writes the scan hook.
"""

from __future__ import annotations

from pathlib import Path

from scripts.quality import push_gate, worktree_scan_hook

HOOK_NAME = "pre-push"
KEPT_NAME = "pre-push.previous"
PREDECESSOR_NAME = "pre-push.legacy"
ORPHAN_NAME = "pre-push.legacy.previous"
PRE_COMMIT_MARKER = "File generated by pre-commit"
OWN_MARKER = "# project push hook, gate version "
REQUIRED_GATE_VERSION = push_gate.GATE_VERSION
GATE_FILE = "scripts/quality/push_gate.py"
# The hook of the version before the gate had a version, byte for byte.
ROUND_TWO_TEXT = (
    "#!/bin/sh\n"
    'refs="$(cat)"\n'
    'printf \'%s\\n\' "$refs" | .venv/bin/python -m scripts.quality.push_gate "$@" || exit $?\n'
    f'previous="$(dirname "$0")/{KEPT_NAME}"\n'
    'if [ -x "$previous" ]; then printf \'%s\\n\' "$refs" | "$previous" "$@"; exit $?; fi\n'
)
_VERSION_CHECK = (
    f"{OWN_MARKER}@VERSION@\n"
    f"version=\"$(sed -n 's/^GATE_VERSION = \\([0-9][0-9]*\\)$/\\1/p' {GATE_FILE} 2>/dev/null)\"\n"
    'if [ -z "$version" ] || [ "$version" -lt @VERSION@ ]; then\n'
    "  echo \"push gate stopped by gate version: this worktree's gate is missing, has no version or is older than version @VERSION@, "
    'which the installed hook requires: run make setup in the main checkout, or rebase this branch on the one that holds the gate" >&2\n'
    "  exit 1\n"
    "fi\n"
)


def hook_text(version: int) -> str:
    """The shared hook for gate ``version``: it refuses a worktree whose gate is missing, has no version constant or is older, and otherwise runs the gate."""
    return ROUND_TWO_TEXT.replace("#!/bin/sh\n", "#!/bin/sh\n" + _VERSION_CHECK.replace("@VERSION@", str(version)), 1)


HOOK_TEXT = hook_text(REQUIRED_GATE_VERSION)
# The guards that earlier versions of this project installed as pre-push.legacy, byte for byte.
_TRACKED = (
    'echo "push gate stopped by tracked changes: tracked files have uncommitted changes, so the checks would not read the pushed commit: '
    'commit or restore them" >&2\n  echo "$changed" >&2\n  exit 1\nfi\n'
)
_PREVIOUS = 'previous="$(dirname "$0")/pre-push.legacy.previous"\n'
PREDECESSOR_TEXTS = (
    '#!/bin/sh\nchanged="$(git status --porcelain --untracked-files=no)"\nif [ -n "$changed" ]; then\n  '
    + _TRACKED
    + _PREVIOUS
    + 'if [ -x "$previous" ]; then exec "$previous" "$@"; fi\n',
    '#!/bin/sh\nrefs="$(git rev-parse --git-path push_gate_refs)"\n{ echo "remote $1"; cat; } > "$refs"\n'
    'sent="$(sed 1d "$refs" | awk \'$2 !~ /^0+$/\')"\n'
    'changed="$(git status --porcelain --untracked-files=no)"\nif [ -n "$changed" ] && [ -n "$sent" ]; then\n  '
    + _TRACKED
    + _PREVIOUS
    + 'if [ -x "$previous" ]; then sed 1d "$refs" | "$previous" "$@"; exit $?; fi\n',
)
PUSH_HOOK = worktree_scan_hook.LegacyHook(HOOK_NAME, KEPT_NAME, HOOK_TEXT)


def hooks_folder(root: Path) -> Path:
    return worktree_scan_hook.hook_path(root, PUSH_HOOK).parent


def predecessors(root: Path) -> list[Path]:
    """The files in the hooks folder that earlier versions left: a shipped guard, a ``pre-push`` script that pre-commit wrote and a hook of this project
    for another gate version or from before the gate had one."""
    hooks = hooks_folder(root)
    legacy, own = hooks / PREDECESSOR_NAME, hooks / HOOK_NAME
    found = [legacy] if legacy.is_file() and legacy.read_text() in PREDECESSOR_TEXTS else []
    if own.is_file():
        text = own.read_text(errors="replace")
        if PRE_COMMIT_MARKER in text or text == ROUND_TWO_TEXT or (OWN_MARKER in text and text != HOOK_TEXT):
            found.append(own)
    return found


def installed(root: Path) -> bool:
    hooks = hooks_folder(root)
    return worktree_scan_hook.installed(root, PUSH_HOOK) and not predecessors(root) and not (hooks / ORPHAN_NAME).exists()


def install(root: Path) -> bool:
    """Remove what earlier versions left, write the hook and return True, or False when nothing changed.

    The owner's hook that a shipped guard kept as ``pre-push.legacy.previous`` is moved to ``pre-push.previous``, so that it keeps running. An older hook that
    cannot be kept raises ``KeptHookError`` before anything is removed.
    """
    hooks = hooks_folder(root)
    stale = predecessors(root)
    orphan = hooks / ORPHAN_NAME
    migrate = orphan.exists() and not (hooks / PREDECESSOR_NAME).exists() or any(path.name == PREDECESSOR_NAME for path in stale) and orphan.exists()
    kept = hooks / KEPT_NAME
    if migrate and kept.exists():
        raise worktree_scan_hook.KeptHookError(
            f"{orphan.name} holds the owner's hook and {kept.name} already holds another: compare the two files, move one away, then run setup again"
        )
    for path in stale:
        path.unlink()
    if migrate:
        orphan.rename(kept)
    return worktree_scan_hook.install(root, PUSH_HOOK) or bool(stale) or migrate
